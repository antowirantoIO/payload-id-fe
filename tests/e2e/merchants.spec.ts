import { expect, test } from '@playwright/test'

test('merchant UI demo supports create, edit, lifecycle, filtering, export and recovery', async ({
  page,
}) => {
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill('admin@payload.local')
  await page.getByLabel('Password', { exact: true }).fill('Admin12345!')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/dashboard/, { timeout: 15_000 })
  await page.goto('/merchants')
  await expect(page).toHaveURL(/\/merchants$/)
  await expect(page.getByRole('heading', { name: 'Merchants', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'DEMO-0001', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Multi-search', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Multi-search', exact: true }).click()
  await page.getByRole('dialog').locator('textarea').fill('DEMO-0001\nDEMO-0002\nDEMO-0001')
  await page.getByRole('button', { name: 'Search merchants', exact: true }).click()
  await expect(page.getByRole('link', { name: 'DEMO-0001', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'DEMO-0002', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'DEMO-0003', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Reset filters', exact: true }).click()
  await page.getByRole('combobox', { name: 'Status', exact: true }).click()
  await page.getByRole('option', { name: 'ACTIVE', exact: true }).click()
  await expect(page.getByRole('link', { name: 'DEMO-0005', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'DEMO-0001', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Saved views', exact: true }).click()
  await page.getByRole('button', { name: 'New view', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Active merchants')
  await page.getByRole('dialog').getByRole('button', { name: 'Save view', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(
    page.getByRole('region', { name: 'Merchants', exact: true }).getByRole('button', {
      name: 'Active merchants',
      exact: true,
    }),
  ).toBeVisible()
  await page.getByRole('button', { name: 'Reset filters', exact: true }).click()
  await page.getByRole('button', { name: 'Add merchant', exact: true }).click()
  await expect(page).toHaveURL(/\/merchants\/create$/)
  const form = page.locator('form')
  await form.getByLabel('Merchant code', { exact: true }).fill('DEMO-E2E')
  await form.getByLabel('Business name', { exact: true }).fill('Demo E2E Merchant')
  await form.getByLabel('Business category', { exact: true }).fill('Retail')
  await form.getByRole('button', { name: 'Continue', exact: true }).click()
  await form.getByLabel('City', { exact: true }).fill('Bandung')
  await form.getByRole('button', { name: 'Continue', exact: true }).click()
  await form.getByRole('button', { name: 'Save merchant', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Demo E2E Merchant', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'PENDING KYC', exact: true }).click()
  await page.getByLabel('Reason for change *', { exact: true }).fill('Begin demo onboarding')
  await page.getByRole('button', { name: 'Confirm change', exact: true }).click()
  await page.getByRole('tab', { name: 'Activity', exact: true }).click()
  await expect(page.getByText(/Begin demo onboarding/)).toBeVisible()
  await page.getByRole('link', { name: 'Edit merchant', exact: true }).click()
  await expect(page).toHaveURL(/\/merchants\/[^/]+\/edit$/)
  await page.getByLabel('Business name', { exact: true }).fill('Demo E2E Updated')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByRole('button', { name: 'Save merchant', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Demo E2E Updated', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Back to merchants', exact: true }).click()
  await page.getByLabel('Search merchants', { exact: true }).fill('DEMO-E2E')
  await expect(page.getByRole('link', { name: 'DEMO-E2E', exact: true })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export results', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('merchants.csv')
  await page.getByLabel('Search merchants', { exact: true }).fill('nothing-matches')
  await expect(page.getByText(/No merchants found/)).toBeVisible()
  await page.getByRole('button', { name: 'Reset filters', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Preview state', exact: true })).toHaveCount(0)
  await expect(page.getByText(/UI demo|synthetic data|simulated load/i)).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'DEMO-E2E', exact: true })).toBeVisible()
  await page.getByLabel('Search merchants', { exact: true }).fill('DEMO-0005')
  await page.getByRole('checkbox', { name: 'Select DEMO-0005', exact: true }).click()
  await page.getByRole('button', { name: 'Suspend', exact: true }).click()
  await page.getByLabel('Reason for change *', { exact: true }).fill('Demo compliance review')
  await page.getByRole('button', { name: 'Confirm change', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'SUSPENDED', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reset filters', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(
    true,
  )
  await page.getByRole('button', { name: 'Add merchant', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(
    true,
  )
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
})
