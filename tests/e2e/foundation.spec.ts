import { expect, test } from '@playwright/test'

test('locale, theme, validation, login, profile, logout and mobile navigation', async ({
  page,
}) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/dashboard')
  await expect(page).toHaveURL(/login/)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/login/)
  await page.getByRole('button', { name: 'Dark', exact: true }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await page.getByRole('button', { name: 'Light', exact: true }).click()
  await expect(page.locator('html')).not.toHaveClass(/dark/)
  await page.getByLabel('Email', { exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Password', { exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'System', exact: true }).click()
  await page.getByRole('button', { name: 'en', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Bahasa Indonesia' }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'id')
  await page.getByRole('button', { name: 'id', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveCount(2)
  await page.getByRole('menuitem', { name: 'English', exact: true }).click()
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill('admin@payload.local')
  await page.getByLabel('Password', { exact: true }).fill('Admin12345!')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/dashboard/, { timeout: 15_000 })
  await expect(page.getByText('admin@payload.local', { exact: true }).last()).toBeVisible()
  await page.route('**/api/iam/me', (route) =>
    route.fulfill({ status: 502, json: { code: 'TEST_OUTAGE' } }),
  )
  await page.reload()
  await expect(page.getByRole('alert').filter({ hasText: 'Unable to load' })).toBeVisible()
  await page.unroute('**/api/iam/me')
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(page.getByText('admin@payload.local', { exact: true }).last()).toBeVisible()
  const session = await page.request.get('/api/auth/session')
  expect(await session.text()).not.toContain('backendToken')
  await page.setViewportSize({ width: 375, height: 812 })
  await page.getByRole('button', { name: 'Open menu', exact: true }).click()
  await expect(page.getByRole('navigation')).toBeVisible()
  await page.getByRole('link', { name: 'Dashboard', exact: true }).last().click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(
    true,
  )
  await page.getByRole('button', { name: 'User menu', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/login/)
  await page.getByRole('button', { name: 'en', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).not.toBeVisible()
  await page.screenshot({ path: 'test-results/login-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
